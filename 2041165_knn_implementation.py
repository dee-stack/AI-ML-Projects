"""IMPORTING DATA"""

titanic= pd.read_csv('/content/final-titanic.csv')

"""DATA DESCRIPTION """

titanic

"""DETAILS OF THE DATASET"""

titanic.info()

"""Description of the attributes

0   PassengerId- Unique ID given to every passenger  
 1   Survived- If the person is servived or not    
 2   Pclass- class of the ticket booked by the passenger       
 3   Name- name of the passenger       
 4   Sex- Gender of the passenger        
 5   Age- age of the passenger        
 6   SibSp- number of siblings or the spouse of the passenger on board       
 7   Parch- number of children on board
 8   Ticket- Number assigned to the ticket      
 9   Fare- price of the ticket         
 10  Cabin- which cabin the passenger is in       
 11  Embarked - which port the passenger got in
"""

titanic.shape

"""Dropping columns which are independent and not considered for the process"""

titanic.drop(['PassengerId','Name','SibSp','Parch','Ticket','Cabin','Embarked'],axis='columns',inplace=True)
titanic.head(3)

"""Dropping Target variable and storing it in a new variable target"""

inputs = titanic.drop('Survived',axis='columns')
target = titanic.Survived

"""One hot encoding- changing values of sex male/female to 0/1"""

dummies = pd.get_dummies(inputs.Sex)
dummies.head(3)

"""combining the independent variables into one dataframe"""

inputs = pd.concat([inputs,dummies],axis='columns')
inputs.head(3)

"""As the attributes sex  is redundant we remove that column

Male column is not required as we are checking for the female survivors
"""

inputs.drop(['Sex'],axis='columns',inplace=True)
inputs.drop(['male'],axis='columns',inplace=True)
inputs.head()

"""CHECKING FOR NULL VALUES"""

inputs.columns[inputs.isna().any()]
inputs.isna().sum()

"""Replacing the null values with mean of the attribute"""

inputs.Age = inputs.Age.fillna(inputs.Age.mean())
inputs.isna().sum()

#inputs.Fare = inputs.Fare.fillna(inputs.Fare.mean())
#inputs.isna().sum()

"""VISUALISATION OF THE DATASET"""

titanic.hist(figsize=(15,10))

"""The graphs depict a graphical representation of frequencies in a histogram. From the graph we can interpret the following: 

Frequency of survivers are less as compared to those who did not survive.

Pclass 3 has most number of passengers.

Most passengers are aged between 20-40 years.

most passengers have 0-1 children


most passengers have 0-1 sibling/spouse

Splitting the dataset into train and test data
"""

X_train, X_test, y_train, y_test = train_test_split(inputs, target, test_size = 0.20, random_state = 0)

"""Feature Scaling: Changing values of the attribute in such a way that all attribute contribute equally to the outcome. Scaling is done to ensure that no higher valued attributes dominate the outcome and lower values are neglected."""

from sklearn.preprocessing import StandardScaler
sc = StandardScaler()
X_train = sc.fit_transform(X_train)
X_test = sc.transform(X_test)

"""After scaling the new model is fit into the existing model for further process where the machine learns from the testing data as it is lazy learning

printing the length of independent variable's train and test data
"""

len(X_train)

len(X_test)

X_train

X_test

y_train

y_test

"""Calulating the distance of every attribute and taking its square root- this is done so that no smaller values are considered for K"""

import math
math.sqrt(len(y_test))

"""Classifing KNN for various values of K"""

# Training the K-NN model on the Training set

knntest3 = KNeighborsClassifier(n_neighbors=3)
knntest3.fit(X_train,y_train)
knntest3.score(X_test,y_test)

knntest5 = KNeighborsClassifier(n_neighbors=1)
knntest5.fit(X_train,y_train)
knntest5.score(X_test,y_test)

knntest7 = KNeighborsClassifier(n_neighbors=7)
knntest7.fit(X_train,y_train)
knntest7.score(X_test,y_test)

"""Calculating Error rates for test scores """

error_rate = []
for i in range(1,13,2):
    knntest = KNeighborsClassifier(n_neighbors=i)
    knntest.fit(X_train,y_train)
    pred_i = knntest.predict(X_test)
    error_rate.append(np.mean(pred_i != y_test))

plt.figure(figsize=(20,6))
plt.plot(range(1,13,2),error_rate,color='blue', 
         marker='o',markerfacecolor='red')
plt.title('Error Rate vs. K Value')
plt.xlabel('K')
plt.ylabel('Error Rate')
#print("Minimum error:-",min(error_rate),"at K =",error_rate.index(min(error_rate)))

"""Creating a predictor variable """

y_pred = knntest7.predict(X_test)
y_pred

"""Creating confusion matrix"""

cm = confusion_matrix(y_test, y_pred)
print(cm)

"""Finding the accurate score """

ac = accuracy_score(y_test, y_pred)
print(ac)

"""Finding F1-score"""

f1 = f1_score(y_test, y_pred)
print(f1)



